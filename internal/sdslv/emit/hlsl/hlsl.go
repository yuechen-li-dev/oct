func typeRef(ref vdmir.Type, name string) string {
	mapped := ref.Name
	switch ref.Kind {
	case vdmir.TypeF32:
		mapped = "float"
	case vdmir.TypeI32:
		mapped = "int"
	case vdmir.TypeU32:
		mapped = "uint"
	case vdmir.TypeUint2:
		mapped = "uint2"
	case vdmir.TypeUint3:
		mapped = "uint3"
	case vdmir.TypeUint4:
		mapped = "uint4"
	case vdmir.TypeVoid:
		mapped = "void"
	}
	if ref.IsArray() && ref.Element != nil {
		elemType := *ref.Element
		count := ref.ArraySize
		if ref.Kind == vdmir.TypeArray {
			elemType, count = fixedArrayStorage(ref)
		}
		elem := typeRef(elemType, "")
		if name == "" {
			return elem
		}
		if ref.Kind == vdmir.TypeArray || ref.Kind == vdmir.TypeNDArray {
			return fmt.Sprintf("%s %s[%d]", elem, hlslIdentifier(name), count)
		}
		return fmt.Sprintf("%s %s[]", elem, hlslIdentifier(name))
	}
	if (ref.Kind == vdmir.TypeTile || ref.Kind == vdmir.TypeRegTile) && ref.Element != nil {
		elem := typeRef(*ref.Element, "")
		if name == "" {
			return elem
		}
		return fmt.Sprintf("%s %s[%d]", elem, hlslIdentifier(name), ref.Rows*ref.Cols)
	}
	if ref.Kind == vdmir.TypeMatrixView {
		if name == "" {
			return "/* matrix_view */"
		}
		return "/* matrix_view */ " + hlslIdentifier(name)
	}
	if ref.Kind == vdmir.TypeBoard {
		mapped = ref.Name
	}
	if name == "" {
		return mapped
	}
	return mapped + " " + hlslIdentifier(name)
}

// fixedArrayStorage maps nested fixed arrays to their compiler-owned linear
// HLSL storage. Tiles, register tiles, matrix views, and runtime arrays retain
// their existing category-specific representations.
func fixedArrayStorage(ref vdmir.Type) (vdmir.Type, int) {
	count := 1
	current := ref
	for current.Kind == vdmir.TypeArray && current.Element != nil {
		count *= current.ArraySize
		current = *current.Element
	}
	return current, count
}

func hlslIdentifier(name string) string {
	switch name {
	case "linear":
		return name + "_"
	default:
		return name
	}
}

func hlslExprPath(path string) string {
	parts := strings.Split(path, ".")
	for i, part := range parts {
		parts[i] = hlslIdentifier(part)
	}
	return strings.Join(parts, ".")
}

func sanitizeName(name string) string {
	var b strings.Builder
	for _, r := range name {
		if (r >= 'A' && r <= 'Z') || (r >= 'a' && r <= 'z') || (r >= '0' && r <= '9') || r == '_' {
			b.WriteRune(r)
		} else {
			b.WriteRune('_')
		}
	}
	return b.String()
}

func hlslIntrinsic(intrinsic vdmir.Intrinsic) string {
	switch intrinsic {
	case vdmir.IntrinsicWorkgroupBarrier:
		return "GroupMemoryBarrierWithGroupSync"
	case vdmir.IntrinsicWorkgroupMemoryBarrier:
		return "GroupMemoryBarrier"
	case vdmir.IntrinsicDot:
		return "dot"
	case vdmir.IntrinsicCross:
		return "cross"
	case vdmir.IntrinsicNormalize:
		return "normalize"
	case vdmir.IntrinsicSaturate:
		return "saturate"
	case vdmir.IntrinsicLerp:
		return "lerp"
	case vdmir.IntrinsicReflect:
		return "reflect"
	case vdmir.IntrinsicUnpackF16x2:
		return "f16tof32"
	case vdmir.IntrinsicBitcast:
		return "asuint" // overridden below by result-aware emission where needed
	case vdmir.IntrinsicConvert:
		return "float"
	default:
		return "GroupMemoryBarrierWithGroupSync"
	}
}

func (e *emitter) m35Intrinsic(x vdmir.IntrinsicCallExpr, args []string) string {
	if len(args) == 0 {
		return hlslIntrinsic(x.Intrinsic) + "()"
	}
	switch x.Intrinsic {
	case vdmir.IntrinsicSampleTexture2D:
		if len(args) != 3 {
			e.err = fmt.Errorf("Sample intrinsic requires 3 lowered arguments")
			return "/* invalid Sample */"
		}
		return args[0] + ".Sample(" + args[1] + ", " + args[2] + ")"
	case vdmir.IntrinsicUnpackF16x2:
		return "f16tof32(uint2((" + args[0] + " & 65535u), (" + args[0] + " >> 16u)))"
	case vdmir.IntrinsicBitcast:
		switch x.Type().Kind {
		case vdmir.TypeF32:
			return "asfloat(" + args[0] + ")"
		case vdmir.TypeI32:
			return "asint(" + args[0] + ")"
		default:
			return "asuint(" + args[0] + ")"
		}
	case vdmir.IntrinsicConvert:
		return typeRef(x.Type(), "") + "(" + args[0] + ")"
	default:
		return hlslIntrinsic(x.Intrinsic) + "(" + strings.Join(args, ", ") + ")"
	}
}

func moduleRequiresCooperativeMatrix(module vdmir.Module) bool {
	for _, requirement := range module.Requirements {
		if requirement.Kind == vdmir.CapabilityCooperativeMatrixF16F32M16N16K16Subgroup {
			return true
		}
	}
	return false
}

