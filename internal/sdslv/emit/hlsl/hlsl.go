func Emit(module vdmir.Module) (string, error) {
	var e emitter
	e.line("// Generated by canonical GoOct SDSL-V via VD-MIR. Do not edit by hand.")
	if module.Namespace != "" {
		e.line("// namespace " + module.Namespace)
	}
	e.line("")
	if moduleRequiresCooperativeMatrix(module) {
		e.emitCooperativeMatrixPreamble()
	}
	for _, alias := range module.TypeAliases {
		suffix := ""
		if alias.Target.Space != "" {
			suffix = " @space(" + alias.Target.Space + ")"
		}
		e.line(fmt.Sprintf("// type %s = %s%s", alias.Name, typeRef(alias.Target, ""), suffix))
		e.line("")
	}
	for _, record := range module.Records {
		e.emitStruct(record.Name, record.Fields)
	}
	for _, board := range module.Boards {
		e.emitStruct(board.Name, board.Fields)
	}
	for _, stream := range module.Streams {
		if len(stream.Fields) == 0 {
			continue
		}
		e.emitStruct(stream.Name, stream.Fields)
	}
	for _, enum := range module.Enums {
		e.emitEnum(enum)
	}
	resources := append([]vdmir.Resource(nil), module.Resources...)
	if len(module.GraphicsEntryPoints) == 0 {
		// Pre-M41 compute artifacts emitted resource bundles in name order. VD-MIR
		// retains canonical source order, while this backend-only compatibility
		// projection preserves production SPIR-V byte identity.
		for start := 0; start < len(resources); {
			end := start + 1
			for end < len(resources) && resources[end].BundleName == resources[start].BundleName {
				end++
			}
			if resources[start].BundleName != "" {
				bundle := resources[start:end]
				sort.SliceStable(bundle, func(i, j int) bool {
					return bundle[i].Name < bundle[j].Name
				})
			}
			start = end
		}
	}
	for _, resource := range resources {
		e.emitResource(resource)
	}
	for _, material := range module.Materials {
		e.emitMaterial(material)
	}
	for _, workgroup := range module.Workgroups {
		e.emitWorkgroup(workgroup)
	}
	if len(module.Resources) > 0 || len(module.Materials) > 0 || len(module.Workgroups) > 0 {
		e.line("")
	}
	entrySet := map[string]vdmir.ComputeEntryPoint{}
	for _, entry := range module.EntryPoints {
		entrySet[entry.EmittedName] = entry
	}
	e.graphicsEntries = map[string]vdmir.GraphicsEntryPoint{}
	for _, entry := range module.GraphicsEntryPoints {
		e.graphicsEntries[entry.EmittedName] = entry
	}
	for _, fn := range module.Functions {
		e.emitFunction(fn, entrySet[fn.EmittedName])
	}
	if e.err != nil {
		return "", e.err
	}
	return e.builder.String(), nil
}

// EmitBenchmark emits one ordinary SDSL-V function behind a minimal compute
// entry point. Benchmark metadata is compiler-owned; this backend only emits
// the already selected entry and deliberately adds no test result ABI.
func EmitBenchmark(module vdmir.Module, function string, workgroup [3]uint32) (string, error) {
	var e emitter
	e.line("// Generated by GoOct SDSL-V M36a. Do not edit.")
	for _, record := range module.Records {
		e.emitStruct(record.Name, record.Fields)
	}
	for _, enum := range module.Enums {
		e.emitEnum(enum)
	}
	for _, resource := range module.Resources {
		e.emitResource(resource)
	}
	var selected *vdmir.ComputeEntryPoint
	for i := range module.EntryPoints {
		if module.EntryPoints[i].FunctionName == function {
			selected = &module.EntryPoints[i]
			break
		}
	}
	if selected != nil {
		for _, fn := range module.Functions {
			if fn.Name == function {
				copy := fn
				copy.EmittedName = "main"
				e.emitFunction(copy, *selected)
				if e.err != nil {
					return "", e.err
				}
				return e.builder.String(), nil
			}
		}
		return "", fmt.Errorf("benchmark entry %s is missing", function)
	}
	emitted := function
	for _, fn := range module.Functions {
		if fn.Name == function {
			emitted = fn.EmittedName
		}
		e.emitFunction(fn, vdmir.ComputeEntryPoint{})
	}
	if e.err != nil {
		return "", e.err
	}
	e.line(fmt.Sprintf("[numthreads(%d, %d, %d)]", workgroup[0], workgroup[1], workgroup[2]))
	e.line("void main(uint3 DispatchThreadID : SV_DispatchThreadID) {")
	e.indent++
	e.line(emitted + "();")
	e.indent--
	e.line("}")
	return e.builder.String(), nil
}

type emitter struct {
	builder         strings.Builder
	indent          int
	tempCounter     int
	viewAliases     map[string]vdmir.RowMajorViewExpr
	testMode        bool
	testFunctions   map[string]bool
	err             error
	graphicsEntries map[string]vdmir.GraphicsEntryPoint
}

// materializedLValue is the shared-backend address boundary. Address
// components are evaluated once in source order, and Text can then be reused
// for both a load and a store without repeating those expressions.
type materializedLValue struct {
	Base              string
	AddressComponents []string
	LinearOffset      string
	Text              string
	ValueType         vdmir.Type
	SourceSpan        source.Span
}

func (e *emitter) emitStruct(name string, fields []vdmir.Field) {
	e.line("struct " + name)
	e.line("{")
	e.indent++
	for _, field := range fields {
		prefix := ""
		if field.HasLocation {
			prefix = fmt.Sprintf("[[vk::location(%d)]] ", field.Location)
		}
		switch field.Interpolation {
		case "flat":
			prefix += "nointerpolation "
		case "noperspective":
			prefix += "noperspective "
		}
		semantic := ""
		if field.Semantic != "" {
			semantic = " : " + field.Semantic
		}
		e.line(fmt.Sprintf("%s%s%s;", prefix, typeRef(field.Type, field.Name), semantic))
	}
	e.indent--
	e.line("};")
	e.line("")
}

func (e *emitter) emitEnum(enum vdmir.Enum) {
	for i, variant := range enum.Variants {
		e.line(fmt.Sprintf("static const int %s_%s = %d;", enum.Name, variant.Name, i))
	}
	for _, variant := range enum.Variants {
		if !variant.HasPayload {
			continue
		}
		e.emitStruct(enumPayloadTypeName(enum.Name, variant.Name), variant.Payload)
	}
	e.line("struct " + enum.Name)
	e.line("{")
	e.indent++
	e.line("int Tag;")
	for _, variant := range enum.Variants {
		if !variant.HasPayload {
			continue
		}
		e.line(fmt.Sprintf("%s %s;", enumPayloadTypeName(enum.Name, variant.Name), hlslIdentifier(variant.Name)))
	}
	e.indent--
	e.line("};")
	e.line("")
	for _, variant := range enum.Variants {
		e.emitEnumConstructor(enum.Name, variant)
	}
}

func (e *emitter) emitEnumConstructor(enumName string, variant vdmir.EnumVariant) {
	params := make([]string, 0, len(variant.Payload))
	for _, field := range variant.Payload {
		params = append(params, typeRef(field.Type, field.Name))
	}
	e.line(fmt.Sprintf("%s %s(%s)", enumName, enumConstructorName(enumName, variant.Name), strings.Join(params, ", ")))
	e.line("{")
	e.indent++
	e.line(fmt.Sprintf("%s value;", enumName))
	e.line(fmt.Sprintf("value.Tag = %s_%s;", enumName, variant.Name))
	for _, field := range variant.Payload {
		e.line(fmt.Sprintf("value.%s.%s = %s;", hlslIdentifier(variant.Name), hlslIdentifier(field.Name), hlslIdentifier(field.Name)))
	}
	e.line("return value;")
	e.indent--
	e.line("}")
	e.line("")
}

func (e *emitter) emitResource(resource vdmir.Resource) {
	prefix := fmt.Sprintf("[[vk::binding(%d, %d)]] ", resource.Binding.Binding, resource.Binding.Set)
	switch resource.Kind {
	case vdmir.ResourceTexture2D:
		e.line(fmt.Sprintf("%sTexture2D<%s> %s;", prefix, typeRef(resource.ElementType, ""), hlslIdentifier(resource.Name)))
	case vdmir.ResourceSampler:
		e.line(fmt.Sprintf("%sSamplerState %s;", prefix, hlslIdentifier(resource.Name)))
	case vdmir.ResourceUniform:
		e.line(fmt.Sprintf("%sConstantBuffer<%s> %s;", prefix, typeRef(resource.ElementType, ""), hlslIdentifier(resource.Name)))
	default:
		elem := typeRef(resource.ElementType, "")
		if resource.Access == vdmir.ResourceReadOnly {
			e.line(fmt.Sprintf("%sStructuredBuffer<%s> %s;", prefix, elem, hlslIdentifier(resource.Name)))
			return
		}
		e.line(fmt.Sprintf("%sRWStructuredBuffer<%s> %s;", prefix, elem, hlslIdentifier(resource.Name)))
	}
}

func (e *emitter) emitMaterial(material vdmir.Material) {
	e.line(fmt.Sprintf("[[vk::binding(%d, %d)]] ConstantBuffer<%s> Material;", material.Binding.Binding, material.Binding.Set, material.TypeName))
}

func (e *emitter) emitWorkgroup(workgroup vdmir.WorkgroupMemoryDecl) {
	if workgroup.IsTile {
		e.line(fmt.Sprintf("groupshared %s %s[%d * %d];", typeRef(workgroup.ElementType, ""), hlslIdentifier(workgroup.Name), workgroup.Rows, workgroup.Cols))
		return
	}
	e.line(fmt.Sprintf("groupshared %s;", typeRef(workgroup.Type, workgroup.Name)))
}

func (e *emitter) emitFunction(fn vdmir.Function, entry vdmir.ComputeEntryPoint) {
	e.viewAliases = map[string]vdmir.RowMajorViewExpr{}
	if entry.EmittedName != "" {
		e.emitEntryParamGlobals(entry)
	}
	if entry.EmittedName != "" {
		e.line(fmt.Sprintf("[numthreads(%d, %d, %d)]", entry.NumThreadsX, entry.NumThreadsY, entry.NumThreadsZ))
	}
	graphics := e.graphicsEntries[fn.EmittedName]
	params := make([]string, 0, len(fn.Params))
	if entry.EmittedName == "" {
		for _, param := range fn.Params {
			params = append(params, typeRef(param.Type, param.Name))
		}
		if e.testMode && e.testFunctions[fn.Name] {
			// Test bodies are ordinary lowered functions, but the generated test
			// wrapper is their compute entry point. Thread the one builtin that
			// test bodies may observe through that wrapper rather than inventing
			// test-only invocation semantics.
			params = append(params, "uint3 DispatchThreadID")
			params = append(params, "inout SdslvTestFailure failure")
		}
	} else {
		for _, builtin := range entry.Builtins {
			if builtin.Referenced {
				if builtin.SPIRVInputBuiltinID == 0 {
					params = append(params, fmt.Sprintf("%s %s : %s", typeRef(builtin.Type, ""), hlslIdentifier(builtin.Name), builtin.Semantic))
				}
			}
		}
	}
	returnSemantic := ""
	if graphics.Stage == vdmir.StagePixel && fn.ReturnType.Kind != vdmir.TypeStream {
		returnSemantic = " : SV_Target0"
	}
	e.line(fmt.Sprintf("%s %s(%s)%s", typeRef(fn.ReturnType, ""), fn.EmittedName, strings.Join(params, ", "), returnSemantic))
	e.line("{")
	e.indent++
	e.emitEntryThreadLocals(entry)
	for _, stmt := range fn.Body.Statements {
		e.emitStmt(stmt)
	}
	e.indent--
	e.line("}")
	e.line("")
}

func (e *emitter) emitEntryParamGlobals(entry vdmir.ComputeEntryPoint) {
	emittedBuiltin := false
	for _, builtin := range entry.Builtins {
		if !builtin.Referenced || builtin.SPIRVInputBuiltinID == 0 {
			continue
		}
		e.line(fmt.Sprintf("[[vk::ext_builtin_input(/* %s */ %d)]]", builtin.Name, builtin.SPIRVInputBuiltinID))
		e.line(fmt.Sprintf("static const %s %s;", typeRef(builtin.Type, ""), hlslIdentifier(builtin.Name)))
		emittedBuiltin = true
	}
	if emittedBuiltin {
		e.line("")
	}
	for _, param := range entry.Params {
		e.line(fmt.Sprintf("[[vk::push_constant]] ConstantBuffer<%s> %s;", typeRef(param.Type, ""), hlslIdentifier(param.Name)))
	}
	if len(entry.Params) > 0 {
		e.line("")
	}
}

func (e *emitter) emitEntryThreadLocals(entry vdmir.ComputeEntryPoint) {
	for _, thread := range entry.ThreadParams {
		e.line(fmt.Sprintf("%s %s;", thread.TypeName, hlslIdentifier(thread.ParamName)))
		for _, field := range thread.Fields {
			value := field.BuiltinName
			if field.BuiltinField != "" {
				value += "." + field.BuiltinField
			}
			e.line(fmt.Sprintf("%s.%s = %s;", hlslIdentifier(thread.ParamName), hlslIdentifier(field.FieldName), hlslExprPath(value)))
		}
	}
	if len(entry.ThreadParams) > 0 {
		e.line("")
	}
}

func (e *emitter) emitBlock(block vdmir.Block) {
	e.line("{")
	e.indent++
	for _, stmt := range block.Statements {
		e.emitStmt(stmt)
	}
	e.indent--
	e.line("}")
}

func (e *emitter) emitStmt(stmt vdmir.Stmt) {
	switch s := stmt.(type) {
	case vdmir.ForeignShaderStmt:
		e.emitForeignSource(s.Provenance.Path, s.SourceLine, s.RawSource)
	case vdmir.LetStmt:
		if s.Value == nil {
			e.line(fmt.Sprintf("%s;", typeRef(s.Type, s.Name)))
			return
		}
		if literal, ok := s.Value.(vdmir.NDArrayLiteral); ok {
			e.line(fmt.Sprintf("%s;", typeRef(s.Type, s.Name)))
			for i, value := range literal.Elements {
				e.line(fmt.Sprintf("%s[%d] = %s;", hlslIdentifier(s.Name), i, e.materializeExpr(value)))
			}
			return
		}
		if fill, ok := s.Value.(vdmir.FillConstruct); ok {
			e.emitFillConstructLet(s, fill)
			return
		}
		if generate, ok := s.Value.(vdmir.GenerateConstruct); ok {
			e.emitGenerateConstructLet(s, generate)
			return
		}
		if zero, ok := s.Value.(vdmir.RegTileZeroExpr); ok {
			e.emitRegTileZeroLet(s.Name, zero.Type())
			return
		}
		if rowMajor, ok := s.Value.(vdmir.RowMajorViewExpr); ok {
			e.viewAliases[s.Name] = rowMajor
			return
		}
		if reduction, ok := s.Value.(vdmir.ReductionExpr); ok {
			e.emitReductionLet(s, reduction)
			return
		}
		if utility, ok := s.Value.(vdmir.WhenUtilityExpr); ok {
			e.emitWhenUtilityLet(s, utility)
			return
		}
		if withExpr, ok := s.Value.(vdmir.WithExpr); ok {
			e.emitWithLet(s, withExpr)
			return
		}
		if matchExpr, ok := s.Value.(vdmir.MatchExpr); ok {
			e.emitMatchLet(s, matchExpr)
			return
		}
		if board, ok := s.Value.(vdmir.BoardConstructExpr); ok {
			e.emitBoardConstructLet(s, board)
			return
		}
		if derive, ok := s.Value.(vdmir.DeriveExpr); ok {
			e.emitDeriveLet(s, derive)
			return
		}
		value := e.materializeExpr(s.Value)
		e.line(fmt.Sprintf("%s = %s;", typeRef(s.Type, s.Name), value))
	case vdmir.AssignStmt:
		if reduction, ok := s.Value.(vdmir.ReductionExpr); ok {
			e.emitReductionAssign(e.expr(s.Target), reduction)
			return
		}
		if utility, ok := s.Value.(vdmir.WhenUtilityExpr); ok {
			e.emitWhenUtilityAssign(e.expr(s.Target), utility)
			return
		}
		if withExpr, ok := s.Value.(vdmir.WithExpr); ok {
			e.emitWithAssign(e.expr(s.Target), withExpr)
			return
		}
		if matchExpr, ok := s.Value.(vdmir.MatchExpr); ok {
			e.emitMatchAssign(e.expr(s.Target), matchExpr)
			return
		}
		if board, ok := s.Value.(vdmir.BoardConstructExpr); ok {
			e.emitBoardConstructAssign(e.expr(s.Target), board)
			return
		}
		if derive, ok := s.Value.(vdmir.DeriveExpr); ok {
			e.emitDeriveAssign(e.expr(s.Target), derive)
			return
		}
		value := e.materializeExpr(s.Value)
		e.line(fmt.Sprintf("%s = %s;", e.expr(s.Target), value))
	case vdmir.TensorAssign:
		e.emitTensorAssign(s, 0)
	case vdmir.GuardedWriteStmt:
		condition := e.materializeExpr(s.Condition)
		e.line("if (" + condition + ")")
		e.line("{")
		e.indent++
		value := e.materializeExpr(s.Value)
		e.line(fmt.Sprintf("%s = %s;", e.expr(s.Target), value))
		e.indent--
		e.line("}")
	case vdmir.ReturnStmt:
		if s.Value == nil {
			e.line("return;")
			return
		}
		if reduction, ok := s.Value.(vdmir.ReductionExpr); ok {
			e.emitReductionReturn(reduction)
			return
		}
		if withExpr, ok := s.Value.(vdmir.WithExpr); ok {
			e.emitWithReturn(withExpr)
			return
		}
		if matchExpr, ok := s.Value.(vdmir.MatchExpr); ok {
			e.emitMatchReturn(matchExpr)
			return
		}
		if board, ok := s.Value.(vdmir.BoardConstructExpr); ok {
			e.emitBoardConstructReturn(board)
			return
		}
		if derive, ok := s.Value.(vdmir.DeriveExpr); ok {
			e.emitDeriveReturn(derive)
			return
		}
		e.line("return " + e.materializeExpr(s.Value) + ";")
	case vdmir.ExprStmt:
		value := e.materializeExpr(s.Value)
		if value != "" {
			e.line(value + ";")
		}
	case vdmir.AssertStmt:
		e.emitTestAssert(s)
	case vdmir.BlockStmt:
		e.emitBlock(s.Body)
	case vdmir.FlowStmt:
		e.emitFlow(s.Flow)
	case vdmir.IfStmt:
		e.emitIfStmt(s)
	case vdmir.ForRangeStmt:
		switch s.LoopHint {
		case vdmir.LoopHintUnroll:
			e.line("[unroll]")
		case vdmir.LoopHintLoop:
			e.line("[loop]")
		}
		loopType := typeRef(s.Type, "")
		start := e.materializeExpr(s.Start)
		end := e.materializeExpr(s.End)
		step := e.materializeExpr(s.Step)
		e.line(fmt.Sprintf("for (%s %s = %s; %s < %s; %s += %s)", loopType, s.Name, start, s.Name, end, s.Name, step))
		e.emitBlock(s.Body)
	}
}

func (e *emitter) emitTensorAssign(stmt vdmir.TensorAssign, depth int) {
	if depth < len(stmt.FreeIndices) {
		index := stmt.FreeIndices[depth]
		e.flowMarker("tensor free-index loop", "", index.Span, index.Name)
		e.line(fmt.Sprintf("for (uint %s = 0u; %s < %du; %s += 1u)", index.ID, index.ID, index.Extent, index.ID))
		e.line("{")
		e.indent++
		e.emitTensorAssign(stmt, depth+1)
		e.indent--
		e.line("}")
		return
	}
	e.flowMarker("tensor statement", "", stmt.SourceSpan, string(stmt.AssignmentKind))
	destination := e.materializeIndexedLValue(stmt.Destination, stmt.SourceSpan)
	if e.err != nil {
		return
	}
	if stmt.AssignmentKind == vdmir.TensorAssignAdd {
		old := e.nextTempWithPrefix("tensor_old")
		e.line(fmt.Sprintf("%s %s = %s;", typeRef(stmt.ElementType, ""), old, destination.Text))
		rhs := e.nextTempWithPrefix("tensor_rhs")
		e.emitTensorValue(rhs, stmt.ElementType, stmt.Value)
		e.flowMarker("tensor final destination write", "", stmt.SourceSpan, "+=")
		e.line(fmt.Sprintf("%s = %s + %s;", destination.Text, old, rhs))
		return
	}
	rhs := e.nextTempWithPrefix("tensor_rhs")
	e.emitTensorValue(rhs, stmt.ElementType, stmt.Value)
	e.flowMarker("tensor final destination write", "", stmt.SourceSpan, "=")
	e.line(fmt.Sprintf("%s = %s;", destination.Text, rhs))
}

func (e *emitter) emitTensorValue(name string, typ vdmir.Type, value vdmir.Expr) {
	result := e.materializeExpr(value)
	e.line(fmt.Sprintf("%s %s = %s;", typeRef(typ, ""), name, result))
}

func (e *emitter) emitTensorReduction(target string, reduction vdmir.TensorReductionExpr, depth int) {
	if depth < len(reduction.Indices) {
		index := reduction.Indices[depth]
		e.flowMarker("tensor reduction loop", "", index.Span, index.Name)
		e.line(fmt.Sprintf("for (uint %s = 0u; %s < %du; %s += 1u)", index.ID, index.ID, index.Extent, index.ID))
		e.line("{")
		e.indent++
		e.emitTensorReduction(target, reduction, depth+1)
		e.indent--
		e.line("}")
		return
	}
	e.flowMarker("tensor reduction body", "", reduction.Span, reduction.Kind)
	body := e.materializeExpr(reduction.Body)
	e.line(fmt.Sprintf("%s = %s + (%s);", target, target, body))
}

func (e *emitter) emitIfStmt(stmt vdmir.IfStmt) {
	condition := e.materializeExpr(stmt.Condition)
	e.line("if (" + condition + ")")
	e.emitBlock(stmt.ThenBody)
	if stmt.ElseBody == nil {
		return
	}
	if len(stmt.ElseBody.Statements) == 1 {
		if nested, ok := stmt.ElseBody.Statements[0].(vdmir.IfStmt); ok {
			nestedCondition := e.materializeExpr(nested.Condition)
			e.line("else " + "if (" + nestedCondition + ")")
			e.emitBlock(nested.ThenBody)
			if nested.ElseBody != nil {
				e.emitElseTail(*nested.ElseBody)
			}
			return
		}
	}
	e.line("else")
	e.emitBlock(*stmt.ElseBody)
}

func (e *emitter) emitElseTail(block vdmir.Block) {
	if len(block.Statements) == 1 {
		if nested, ok := block.Statements[0].(vdmir.IfStmt); ok {
			nestedCondition := e.materializeExpr(nested.Condition)
			e.line("else " + "if (" + nestedCondition + ")")
			e.emitBlock(nested.ThenBody)
			if nested.ElseBody != nil {
				e.emitElseTail(*nested.ElseBody)
			}
			return
		}
	}
	e.line("else")
	e.emitBlock(block)
}

// emitFlow is the shared backend execution model for M31b flows.  State IDs
// are declaration-order IDs from validated VD-MIR; 0xffffffff is FlowComplete.
func (e *emitter) emitFlow(flow vdmir.Flow) {
	if err := validateFlow(flow); err != nil {
		e.err = err
		return
	}
	name := "__flow_" + sanitizeName(flow.Name) + "_" + fmt.Sprintf("%d", e.tempCounter)
	e.tempCounter++
	state, complete := name+"_state", "4294967295u"
	dispatcherSpan := flow.SourceSpan
	if !dispatcherSpan.Known() && len(flow.States) != 0 {
		dispatcherSpan = flow.States[flow.Entry].NameSpan
	}
	e.flowMarker("flow dispatcher", flow.Provenance.Path, dispatcherSpan, flow.Name)
	e.line(fmt.Sprintf("uint %s = %du;", state, flow.Entry))
	top, stack := name+"_stack_top", name+"_return_stack"
	if flow.HasPushPop {
		e.flowMarker("flow stack", flow.Provenance.Path, dispatcherSpan, fmt.Sprintf("MaxStackDepth=%d", flow.MaxStackDepth))
		e.line(fmt.Sprintf("uint %s = 0u;", top))
		e.line(fmt.Sprintf("uint %s[%d];", stack, flow.MaxStackDepth))
	}
	e.line(fmt.Sprintf("while (%s != %s)", state, complete))
	e.line("{")
	e.indent++
	e.line(fmt.Sprintf("switch (%s)", state))
	e.line("{")
	e.indent++
	for _, s := range flow.States {
		e.flowMarker("flow state", flow.Provenance.Path, s.NameSpan, s.Name)
		e.line(fmt.Sprintf("case %du:", s.ID))
		e.line("{")
		e.indent++
		for _, stmt := range s.Body.Statements {
			e.emitStmt(stmt)
		}
		e.emitFlowTerminator(s.Terminator, state, top, stack, complete)
		e.line("break;")
		e.indent--
		e.line("}")
	}
	e.line("default:")
	e.line("{")
	e.indent++
	e.line(state + " = " + complete + ";")
	e.line("break;")
	e.indent--
	e.line("}")
	e.indent--
	e.line("}")
	e.indent--
	e.line("}")
}

func (e *emitter) emitFlowTerminator(t vdmir.FlowTerminator, state, top, stack, complete string) {
	value := func(id int) string {
		if id == vdmir.FlowCompleteStateID {
			return complete
		}
		return fmt.Sprintf("%du", id)
	}
	switch t.Kind {
	case vdmir.FlowTerminatorFallthrough, vdmir.FlowTerminatorGoto:
		e.flowMarker("flow terminator", "", t.Span, string(t.Kind))
		e.line(state + " = " + value(t.Target) + ";")
	case vdmir.FlowTerminatorFinish:
		e.flowMarker("flow terminator", "", t.Span, string(t.Kind))
		e.line(state + " = " + complete + ";")
	case vdmir.FlowTerminatorPush:
		e.flowMarker("flow terminator", "", t.Span, fmt.Sprintf("%s target=%s return=%s", t.Kind, value(t.Target), value(t.ReturnTo)))
		e.flowMarker("flow stack push", "", t.Span, "")
		e.line(fmt.Sprintf("%s[%s] = %s;", stack, top, value(t.ReturnTo)))
		e.line(top + " += 1u;")
		e.line(state + " = " + value(t.Target) + ";")
	case vdmir.FlowTerminatorPop:
		e.flowMarker("flow terminator", "", t.Span, string(t.Kind))
		e.flowMarker("flow stack pop", "", t.Span, "")
		e.line(top + " -= 1u;")
		e.line(state + " = " + stack + "[" + top + "];")
	}
}

func (e *emitter) flowMarker(kind, path string, span source.Span, detail string) {
	if !span.Known() {
		if detail != "" {
			e.line("// " + kind + ": " + detail)
			return
		}
		e.line("// " + kind)
		return
	}
	location := fmt.Sprintf("%d:%d", span.Start.Line, span.Start.Column)
	if path != "" {
		location = path + ":" + location
	}
	if detail != "" {
		e.line(fmt.Sprintf("// %s %s %s", kind, location, detail))
		return
	}
	e.line(fmt.Sprintf("// %s %s", kind, location))
}

func validateFlow(flow vdmir.Flow) error {
	if flow.Entry < 0 || flow.Entry >= len(flow.States) {
		return fmt.Errorf("malformed FlowProgram %s: invalid entry state ID %d", flow.Name, flow.Entry)
	}
	if flow.HasPushPop && flow.MaxStackDepth == 0 {
		return fmt.Errorf("malformed FlowProgram %s: push/pop requires positive MaxStackDepth", flow.Name)
	}
	seen := map[int]bool{}
	for _, s := range flow.States {
		if s.ID < 0 || seen[s.ID] {
			return fmt.Errorf("malformed FlowProgram %s: duplicate or invalid state ID %d", flow.Name, s.ID)
		}
		seen[s.ID] = true
	}
	valid := func(id int) bool { return id == vdmir.FlowCompleteStateID || seen[id] }
	for _, s := range flow.States {
		switch t := s.Terminator; t.Kind {
		case vdmir.FlowTerminatorFallthrough, vdmir.FlowTerminatorGoto:
			if !valid(t.Target) {
				return fmt.Errorf("malformed FlowProgram %s: invalid target state ID %d", flow.Name, t.Target)
			}
		case vdmir.FlowTerminatorPush:
			if !flow.HasPushPop || !valid(t.Target) || !valid(t.ReturnTo) {
				return fmt.Errorf("malformed FlowProgram %s: invalid push terminator", flow.Name)
			}
		case vdmir.FlowTerminatorPop:
			if !flow.HasPushPop {
				return fmt.Errorf("malformed FlowProgram %s: pop without return-stack contract", flow.Name)
			}
		case vdmir.FlowTerminatorFinish:
		default:
			return fmt.Errorf("malformed FlowProgram %s: unsupported terminator %q", flow.Name, t.Kind)
		}
	}
	return nil
}

