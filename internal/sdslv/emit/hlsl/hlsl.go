func (e *emitter) whenUtility(expr vdmir.WhenUtilityExpr) string {
	var b strings.Builder
	b.WriteString("([&]() { auto __sdslv_best = ")
	b.WriteString(e.expr(expr.Else))
	b.WriteString("; float __sdslv_score = -3.402823466e+38F; ")
	for _, c := range expr.Cases {
		b.WriteString("if (")
		b.WriteString(e.expr(c.Guard))
		b.WriteString(" && (")
		b.WriteString(e.expr(c.Score))
		b.WriteString(" > __sdslv_score)) { __sdslv_score = ")
		b.WriteString(e.expr(c.Score))
		b.WriteString("; __sdslv_best = ")
		b.WriteString(e.expr(c.Value))
		b.WriteString("; } ")
	}
	b.WriteString("return __sdslv_best; })()")
	return b.String()
}

func (e *emitter) index2D(expr vdmir.Index2DExpr) string {
	target := e.expr(expr.Target)
	stride := expr.Stride
	if stride == nil {
		if ref, ok := expr.Target.(vdmir.VarRefExpr); ok {
			if alias, exists := e.viewAliases[ref.Name]; exists {
				target = e.expr(alias.Buffer)
				stride = alias.Cols
			}
		}
	}
	strideText := "0"
	if stride != nil {
		strideText = e.expr(stride)
	}
	return target + "[((" + e.expr(expr.Row) + ") * (" + strideText + ")) + (" + e.expr(expr.Col) + ")]"
}

func (e *emitter) indexN(expr vdmir.IndexNExpr) string {
	if expr.Layout != vdmir.IndexLayoutRowMajorLinear || len(expr.Indices) == 0 || len(expr.Indices) != len(expr.Extents) {
		e.err = fmt.Errorf("invalid rank-general fixed-array linearization metadata")
		return "0"
	}
	offset := e.expr(expr.Indices[0])
	for axis := 1; axis < len(expr.Indices); axis++ {
		offset = fmt.Sprintf("((%s * %du) + %s)", offset, expr.Extents[axis], e.expr(expr.Indices[axis]))
	}
	return e.expr(expr.Target) + "[" + offset + "]"
}

func (e *emitter) emitRegTileZeroLet(name string, typ vdmir.Type) {
	e.line(fmt.Sprintf("%s;", typeRef(typ, name)))
	elemType := elementTypeForArrayish(typ)
	for i := 0; i < typ.ArraySize; i++ {
		e.line(fmt.Sprintf("%s[%d] = %s;", name, i, zeroLiteral(elemType)))
	}
}

func validFixedShape(ref vdmir.Type) bool {
	_, _, ok := fixedShapeMetadata(ref)
	return ok
}

// emitFillConstructLet evaluates Value once, then reuses the materialized
// scalar for all compiler-owned flat row-major stores.
func (e *emitter) emitFillConstructLet(stmt vdmir.LetStmt, fill vdmir.FillConstruct) {
	elemType, shape, ok := fixedShapeMetadata(stmt.Type)
	_, _, fillOK := fixedShapeMetadata(fill.Type())
	if !ok || !fillOK {
		e.err = fmt.Errorf("malformed fixed-shape Fill metadata")
		return
	}
	e.line(fmt.Sprintf("%s;", typeRef(stmt.Type, stmt.Name)))
	temp := e.nextTempWithPrefix("fill")
	e.line(fmt.Sprintf("%s = %s;", typeRef(elemType, temp), e.materializeExpr(fill.Value)))
	count := 1
	for _, extent := range shape {
		count *= int(extent)
	}
	for i := 0; i < count; i++ {
		e.line(fmt.Sprintf("%s[%d] = %s;", hlslIdentifier(stmt.Name), i, temp))
	}
}

// emitGenerateConstructLet uses source binder order as loop nesting order;
// indexN owns the one row-major linearization formula used by ndarray access.
func (e *emitter) emitGenerateConstructLet(stmt vdmir.LetStmt, generate vdmir.GenerateConstruct) {
	_, shape, ok := fixedShapeMetadata(stmt.Type)
	_, _, generateOK := fixedShapeMetadata(generate.Type())
	if !ok || !generateOK || len(generate.Binders) != len(shape) {
		e.err = fmt.Errorf("malformed fixed-shape Generate metadata")
		return
	}
	e.line(fmt.Sprintf("%s;", typeRef(stmt.Type, stmt.Name)))
	indices := make([]vdmir.Expr, len(generate.Binders))
	for i, binder := range generate.Binders {
		indices[i] = vdmir.VarRefExpr{ExprType: vdmir.Type{Kind: vdmir.TypeU32, Name: "u32"}, Name: binder, Kind: vdmir.VarLocal}
	}
	var emitAxis func(int)
	emitAxis = func(axis int) {
		if axis == len(indices) {
			destination := e.materializeIndexedLValue(vdmir.IndexNExpr{
				Target:  vdmir.VarRefExpr{ExprType: stmt.Type, Name: stmt.Name, Kind: vdmir.VarLocal},
				Indices: indices,
				Extents: shape,
				Layout:  vdmir.IndexLayoutRowMajorLinear,
			}, source.Span{})
			if e.err != nil {
				return
			}
			value := e.materializeExpr(generate.Body)
			e.line(fmt.Sprintf("%s = %s;", destination.Text, value))
			return
		}
		name := hlslIdentifier(generate.Binders[axis])
		e.line(fmt.Sprintf("for (uint %s = 0u; %s < %du; ++%s)", name, name, shape[axis], name))
		e.line("{")
		e.indent++
		emitAxis(axis + 1)
		e.indent--
		e.line("}")
	}
	emitAxis(0)
}

func fixedShapeMetadata(ref vdmir.Type) (vdmir.Type, []uint32, bool) {
	switch ref.Kind {
	case vdmir.TypeNDArray:
		if ref.Element == nil || len(ref.Shape) == 0 {
			return vdmir.Type{}, nil, false
		}
		return *ref.Element, append([]uint32(nil), ref.Shape...), true
	case vdmir.TypeArray:
		if len(ref.Shape) == 0 {
			return vdmir.Type{}, nil, false
		}
		elem, _ := fixedArrayStorage(ref)
		return elem, append([]uint32(nil), ref.Shape...), true
	default:
		return vdmir.Type{}, nil, false
	}
}

func elementTypeForArrayish(ref vdmir.Type) vdmir.Type {
	if ref.Element == nil {
		return vdmir.Type{}
	}
	return *ref.Element
}

