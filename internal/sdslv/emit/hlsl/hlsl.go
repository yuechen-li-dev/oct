package hlsl

import (
	"fmt"
	"strings"

	"github.com/yuechen-li-dev/oct/internal/sdslv/vdmir"
)

func Emit(module vdmir.Module) (string, error) {
	var e emitter
	e.line("// Generated by GoOct SDSL-V M1 via VD-MIR. Do not edit by hand.")
	if module.Namespace != "" {
		e.line("// namespace " + module.Namespace)
	}
	e.line("")
	for _, alias := range module.TypeAliases {
		e.line(fmt.Sprintf("// type %s = %s", alias.Name, typeRef(alias.Target, "")))
		e.line("")
	}
	for _, record := range module.Records {
		e.emitRecord(record)
	}
	for _, enum := range module.Enums {
		e.emitEnum(enum)
	}
	for _, resource := range module.Resources {
		e.emitResource(resource)
	}
	if len(module.Resources) > 0 {
		e.line("")
	}
	entrySet := map[string]vdmir.ComputeEntryPoint{}
	for _, entry := range module.EntryPoints {
		entrySet[entry.EmittedName] = entry
	}
	for _, fn := range module.Functions {
		e.emitFunction(fn, entrySet[fn.EmittedName])
	}
	return e.builder.String(), nil
}

type emitter struct {
	builder strings.Builder
	indent  int
}

func (e *emitter) emitRecord(record vdmir.Record) {
	e.line("struct " + record.Name)
	e.line("{")
	e.indent++
	for _, field := range record.Fields {
		e.line(fmt.Sprintf("%s;", typeRef(field.Type, field.Name)))
	}
	e.indent--
	e.line("};")
	e.line("")
}

func (e *emitter) emitEnum(enum vdmir.Enum) {
	for i, variant := range enum.Variants {
		e.line(fmt.Sprintf("static const int %s_%s = %d;", enum.Name, variant, i))
	}
	e.line("")
}

func (e *emitter) emitResource(resource vdmir.Resource) {
	elem := typeRef(resource.ElementType, "")
	if resource.Access == vdmir.ResourceReadOnly {
		e.line(fmt.Sprintf("Buffer<%s> %s;", elem, resource.Name))
		return
	}
	e.line(fmt.Sprintf("RWBuffer<%s> %s;", elem, resource.Name))
}

func (e *emitter) emitFunction(fn vdmir.Function, entry vdmir.ComputeEntryPoint) {
	if entry.EmittedName != "" {
		e.line(fmt.Sprintf("[numthreads(%d, %d, %d)]", entry.NumThreadsX, entry.NumThreadsY, entry.NumThreadsZ))
	}
	params := make([]string, 0, len(fn.Params)+len(entry.Builtins))
	for _, param := range fn.Params {
		params = append(params, typeRef(param.Type, param.Name))
	}
	for _, builtin := range entry.Builtins {
		params = append(params, fmt.Sprintf("%s %s : %s", typeRef(builtin.Type, ""), builtin.Name, builtin.Semantic))
	}
	e.line(fmt.Sprintf("%s %s(%s)", typeRef(fn.ReturnType, ""), fn.EmittedName, strings.Join(params, ", ")))
	e.emitBlock(fn.Body)
	e.line("")
}

func (e *emitter) emitBlock(block vdmir.Block) {
	e.line("{")
	e.indent++
	for _, stmt := range block.Statements {
		e.emitStmt(stmt)
	}
	e.indent--
	e.line("}")
}

func (e *emitter) emitStmt(stmt vdmir.Stmt) {
	switch s := stmt.(type) {
	case vdmir.LetStmt:
		if s.Value == nil {
			e.line(fmt.Sprintf("%s;", typeRef(s.Type, s.Name)))
			return
		}
		if utility, ok := s.Value.(vdmir.WhenUtilityExpr); ok {
			e.emitWhenUtilityLet(s, utility)
			return
		}
		e.line(fmt.Sprintf("%s = %s;", typeRef(s.Type, s.Name), e.expr(s.Value)))
	case vdmir.AssignStmt:
		if utility, ok := s.Value.(vdmir.WhenUtilityExpr); ok {
			e.emitWhenUtilityAssign(e.expr(s.Target), utility)
			return
		}
		e.line(fmt.Sprintf("%s = %s;", e.expr(s.Target), e.expr(s.Value)))
	case vdmir.ReturnStmt:
		if s.Value == nil {
			e.line("return;")
		} else {
			e.line("return " + e.expr(s.Value) + ";")
		}
	case vdmir.ExprStmt:
		e.line(e.expr(s.Value) + ";")
	case vdmir.IfStmt:
		e.line("if (" + e.expr(s.Condition) + ")")
		e.emitBlock(s.ThenBody)
		if s.ElseBody != nil {
			e.line("else")
			e.emitBlock(*s.ElseBody)
		}
	case vdmir.ForRangeStmt:
		loopType := typeRef(s.Type, "")
		e.line(fmt.Sprintf("for (%s %s = %s; %s < %s; %s += %s)", loopType, s.Name, e.expr(s.Start), s.Name, e.expr(s.End), s.Name, e.expr(s.Step)))
		e.emitBlock(s.Body)
	}
}

func (e *emitter) emitWhenUtilityLet(stmt vdmir.LetStmt, utility vdmir.WhenUtilityExpr) {
	e.line(fmt.Sprintf("%s = %s;", typeRef(stmt.Type, stmt.Name), e.expr(utility.Else)))
	e.emitWhenUtilityAssign(stmt.Name, utility)
}

func (e *emitter) emitWhenUtilityAssign(target string, utility vdmir.WhenUtilityExpr) {
	scoreName := "__sdslv_" + sanitizeName(target) + "_score"
	e.line(fmt.Sprintf("float %s = -3.402823466e+38F;", scoreName))
	for _, c := range utility.Cases {
		score := e.expr(c.Score)
		e.line(fmt.Sprintf("if (%s && (%s > %s))", e.expr(c.Guard), score, scoreName))
		e.line("{")
		e.indent++
		e.line(fmt.Sprintf("%s = %s;", scoreName, score))
		e.line(fmt.Sprintf("%s = %s;", target, e.expr(c.Value)))
		e.indent--
		e.line("}")
	}
}

func (e *emitter) expr(expr vdmir.Expr) string {
	switch x := expr.(type) {
	case vdmir.LiteralExpr:
		return x.Value
	case vdmir.VarRefExpr:
		return x.Name
	case vdmir.FieldAccessExpr:
		return e.expr(x.Target) + "." + x.Field
	case vdmir.IndexExpr:
		return e.expr(x.Target) + "[" + e.expr(x.Index) + "]"
	case vdmir.CallExpr:
		args := make([]string, 0, len(x.Arguments))
		for _, arg := range x.Arguments {
			args = append(args, e.expr(arg))
		}
		return e.expr(x.Callee) + "(" + strings.Join(args, ", ") + ")"
	case vdmir.BinaryExpr:
		return "(" + e.expr(x.Left) + " " + x.Operator + " " + e.expr(x.Right) + ")"
	case vdmir.UnaryExpr:
		return x.Operator + e.expr(x.Operand)
	case vdmir.WhenUtilityExpr:
		return e.whenUtility(x)
	default:
		return "/* unsupported */"
	}
}

func (e *emitter) whenUtility(expr vdmir.WhenUtilityExpr) string {
	var b strings.Builder
	b.WriteString("([&]() { auto __sdslv_best = ")
	b.WriteString(e.expr(expr.Else))
	b.WriteString("; float __sdslv_score = -3.402823466e+38F; ")
	for _, c := range expr.Cases {
		b.WriteString("if (")
		b.WriteString(e.expr(c.Guard))
		b.WriteString(" && (")
		b.WriteString(e.expr(c.Score))
		b.WriteString(" > __sdslv_score)) { __sdslv_score = ")
		b.WriteString(e.expr(c.Score))
		b.WriteString("; __sdslv_best = ")
		b.WriteString(e.expr(c.Value))
		b.WriteString("; } ")
	}
	b.WriteString("return __sdslv_best; })()")
	return b.String()
}

func (e *emitter) line(text string) {
	for i := 0; i < e.indent; i++ {
		e.builder.WriteString("    ")
	}
	e.builder.WriteString(text)
	e.builder.WriteByte('\n')
}

func typeRef(ref vdmir.Type, name string) string {
	mapped := ref.Name
	switch ref.Kind {
	case vdmir.TypeF32:
		mapped = "float"
	case vdmir.TypeI32:
		mapped = "int"
	case vdmir.TypeU32:
		mapped = "uint"
	case vdmir.TypeVoid:
		mapped = "void"
	}
	if ref.IsArray() && ref.Element != nil {
		elem := typeRef(*ref.Element, "")
		if name == "" {
			return elem
		}
		if ref.Kind == vdmir.TypeArray {
			return fmt.Sprintf("%s %s[%d]", elem, name, ref.ArraySize)
		}
		return fmt.Sprintf("%s %s[]", elem, name)
	}
	if name == "" {
		return mapped
	}
	return mapped + " " + name
}

func sanitizeName(name string) string {
	var b strings.Builder
	for _, r := range name {
		if (r >= 'A' && r <= 'Z') || (r >= 'a' && r <= 'z') || (r >= '0' && r <= '9') || r == '_' {
			b.WriteRune(r)
		} else {
			b.WriteRune('_')
		}
	}
	return b.String()
}
