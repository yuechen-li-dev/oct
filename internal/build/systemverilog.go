func uniqueSVName(base string, used map[string]int) string {
	if used[base] == 0 {
		used[base] = 1
		return base
	}
	for suffix := used[base]; ; suffix++ {
		candidate := base + "_oct" + strconv.Itoa(suffix)
		if used[candidate] == 0 {
			used[base] = suffix + 1
			used[candidate] = 1
			return candidate
		}
	}
}
func sanitizeSVIdentifier(name string) string {
	var b strings.Builder
	for i, r := range name {
		valid := r == '_' || r == '$' || unicode.IsLetter(r) || (i > 0 && unicode.IsDigit(r))
		if valid && r <= unicode.MaxASCII {
			b.WriteRune(r)
		} else {
			b.WriteByte('_')
		}
	}
	result := b.String()
	if result == "" || unicode.IsDigit(rune(result[0])) || svKeywords[result] {
		result = "oct_" + result
	}
	return result
}

var svKeywords = func() map[string]bool {
	words := strings.Fields("always always_comb always_ff assign automatic begin case default else end endcase endfunction endmodule for function if initial input integer logic module output reg signed unique wire")
	result := make(map[string]bool, len(words))
	for _, word := range words {
		result[word] = true
	}
	return result
}()
