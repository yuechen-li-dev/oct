package build

import (
	"fmt"
	"sort"
	"strconv"
	"strings"
	"unicode"
)

const generatedSystemVerilogHeader = "// Code generated by Veril-Oct. DO NOT EDIT.\n"

// CheckSystemVerilogLegal is the explicit capability boundary between the
// backend-neutral MIR and the deliberately small combinational M0 backend.
func CheckSystemVerilogLegal(module MIRModule) error {
	if len(module.Flows) != 0 {
		return fmt.Errorf("Verilog profile does not support FLOW in M0")
	}
	if len(module.Records) != 0 || len(module.Enums) != 0 || len(module.Refinements) != 0 {
		return fmt.Errorf("Verilog profile M0 supports only Bool and Int scalar values")
	}
	for _, fn := range module.Functions {
		if fn.Package != module.EntryPackage {
			return fmt.Errorf("Verilog profile does not support imported package function %s.%s in M0", fn.Package, fn.Name)
		}
		if fn.IsFallible {
			return fmt.Errorf("Verilog profile does not support fallible function %s", fn.Name)
		}
		if len(fn.CaptureEnv) != 0 {
			return fmt.Errorf("Verilog profile does not support closures or captured function values in M0")
		}
		if fn.UsesUtilityWhen {
			return fmt.Errorf("Verilog profile does not support utility when in M0")
		}
		if err := checkSVType(fn.Return); err != nil {
			return fmt.Errorf("function %s return: %w", fn.Name, err)
		}
		for _, field := range append(append([]MIRField(nil), fn.Params...), fn.Locals...) {
			if err := checkSVType(field.Type); err != nil {
				return fmt.Errorf("function %s value %s: %w", fn.Name, sourceOrMIRName(field), err)
			}
		}
		if len(fn.Blocks) != 1 || fn.Blocks[0].Label != "entry" {
			return fmt.Errorf("Verilog profile does not support branch/control-flow lowering in M0")
		}
		for _, stmt := range fn.Blocks[0].Statements {
			switch st := stmt.(type) {
			case MIRAssign:
				if st.Target == "_" {
					return fmt.Errorf("Verilog profile does not support discarded runtime expressions in M0")
				}
				if err := checkSVValue(st.Value); err != nil {
					return fmt.Errorf("function %s assignment: %w", fn.Name, err)
				}
			case MIRConstructArray:
				return fmt.Errorf("Verilog profile does not support dynamic array allocation")
			case MIRCall:
				if st.Builtin {
					return fmt.Errorf("Verilog profile does not support builtin %s in M0", st.Callee)
				}
				return fmt.Errorf("Verilog profile does not support inter-function calls in M0")
			case MIRGenericOctxiliaryCall:
				return fmt.Errorf("Verilog profile does not support native/Octxiliary calls")
			case MIRBatchMap:
				return fmt.Errorf("Verilog profile does not support batch in M0")
			default:
				return fmt.Errorf("Verilog profile does not support MIR statement %T in M0", stmt)
			}
		}
		ret, ok := fn.Blocks[0].Terminator.(MIRReturn)
		if !ok || ret.Value == nil {
			return fmt.Errorf("Verilog profile M0 requires a straight-line value return in function %s", fn.Name)
		}
		if err := checkSVValue(ret.Value); err != nil {
			return fmt.Errorf("function %s return: %w", fn.Name, err)
		}
	}
	if len(module.Functions) == 0 {
		return fmt.Errorf("Verilog profile requires at least one function module")
	}
	return nil
}

func checkSVType(typ string) error {
	switch typ {
	case "Bool", "Int":
		return nil
	case "String":
		return fmt.Errorf("Verilog profile does not support String values")
	default:
		if strings.HasSuffix(typ, "[]") || strings.HasPrefix(typ, "[]") {
			return fmt.Errorf("Verilog profile does not support dynamic array values")
		}
		return fmt.Errorf("Verilog profile does not support %s values in M0", typ)
	}
}

func checkSVValue(value MIRValue) error {
	if value == nil {
		return fmt.Errorf("Verilog profile does not support an empty MIR value")
	}
	switch v := value.(type) {
	case MIRLiteral:
		if err := checkSVType(v.Type); err != nil {
			return err
		}
		if v.Type == "Bool" && v.Value != "true" && v.Value != "false" {
			return fmt.Errorf("Verilog profile received invalid Bool literal %q", v.Value)
		}
		if v.Type == "Int" {
			if _, err := strconv.ParseInt(v.Value, 10, 64); err != nil {
				return fmt.Errorf("Verilog profile Int literal %q is outside the signed 64-bit hardware range", v.Value)
			}
		}
		return nil
	case MIRLocal:
		if v.Type == "" {
			return nil
		}
		return checkSVType(v.Type)
	case MIRUnary:
		if v.Op != "-" && v.Op != "!" && v.Op != "+" {
			return fmt.Errorf("Verilog profile does not support unary operator %s", v.Op)
		}
		return checkSVValue(v.Value)
	case MIRBinary:
		switch v.Op {
		case "+", "-", "*", "==", "!=", "<", "<=", ">", ">=", "&&", "||":
		default:
			return fmt.Errorf("Verilog profile does not support binary operator %s", v.Op)
		}
		if err := checkSVValue(v.Left); err != nil {
			return err
		}
		return checkSVValue(v.Right)
	case MIRConvert:
		return fmt.Errorf("Verilog profile does not support conversion to %s in M0", v.TargetType)
	case MIRBackendValue:
		return fmt.Errorf("Verilog profile does not support MIRBackendValue (%s); backend-shaped values are never parsed by the SystemVerilog backend", v.Reason)
	case MIRFunctionRef:
		return fmt.Errorf("Verilog profile does not support function values in M0")
	case MIRClone:
		return fmt.Errorf("Verilog profile does not support heap/value cloning")
	default:
		return fmt.Errorf("Verilog profile does not support MIR value %T in M0", value)
	}
}

func emitSystemVerilog(module MIRModule) (string, error) {
	var b strings.Builder
	b.WriteString(generatedSystemVerilogHeader)
	b.WriteString("// Oct Int hardware policy: signed 64-bit two's-complement.\n\n")
	moduleNames := map[string]int{}
	for index, fn := range module.Functions {
		if index != 0 {
			b.WriteByte('\n')
		}
		moduleName := uniqueSVName(sanitizeSVIdentifier(fn.Name), moduleNames)
		if err := emitSVFunction(&b, moduleName, fn); err != nil {
			return "", err
		}
	}
	return b.String(), nil
}

func emitSVFunction(b *strings.Builder, moduleName string, fn MIRFunction) error {
	used := map[string]int{"Result": 1}
	names := make(map[string]string, len(fn.Params)+len(fn.Locals))
	for _, field := range fn.Params {
		names[field.Name] = uniqueSVName(sanitizeSVIdentifier(sourceOrMIRName(field)), used)
	}
	for _, field := range fn.Locals {
		names[field.Name] = uniqueSVName(sanitizeSVIdentifier(sourceOrMIRName(field)), used)
	}
	fmt.Fprintf(b, "module %s(\n", moduleName)
	ports := make([]string, 0, len(fn.Params)+1)
	for _, param := range fn.Params {
		ports = append(ports, fmt.Sprintf("    input  %s %s", svType(param.Type), names[param.Name]))
	}
	ports = append(ports, fmt.Sprintf("    output %s Result", svType(fn.Return)))
	b.WriteString(strings.Join(ports, ",\n"))
	b.WriteString("\n);\n")
	if len(fn.Locals) > 0 {
		b.WriteByte('\n')
		for _, local := range fn.Locals {
			fmt.Fprintf(b, "%s %s;\n", svType(local.Type), names[local.Name])
		}
	}
	b.WriteString("\nalways_comb begin\n")
	for _, stmt := range fn.Blocks[0].Statements {
		assign := stmt.(MIRAssign)
		value, err := emitSVValue(assign.Value, names)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "    %s = %s;\n", names[assign.Target], value)
	}
	ret := fn.Blocks[0].Terminator.(MIRReturn)
	value, err := emitSVValue(ret.Value, names)
	if err != nil {
		return err
	}
	fmt.Fprintf(b, "    Result = %s;\n", value)
	b.WriteString("end\n\nendmodule\n")
	return nil
}

func emitSVValue(value MIRValue, names map[string]string) (string, error) {
	switch v := value.(type) {
	case MIRLiteral:
		if v.Type == "Bool" {
			if v.Value == "true" {
				return "1'b1", nil
			}
			return "1'b0", nil
		}
		return "64'sd" + v.Value, nil
	case MIRLocal:
		if name, ok := names[v.Name]; ok {
			return name, nil
		}
		return sanitizeSVIdentifier(v.Name), nil
	case MIRUnary:
		inner, err := emitSVValue(v.Value, names)
		return "(" + v.Op + inner + ")", err
	case MIRBinary:
		left, err := emitSVValue(v.Left, names)
		if err != nil {
			return "", err
		}
		right, err := emitSVValue(v.Right, names)
		if err != nil {
			return "", err
		}
		return "(" + left + " " + v.Op + " " + right + ")", nil
	default:
		return "", fmt.Errorf("emit unsupported SystemVerilog MIR value %T", value)
	}
}

func svType(typ string) string {
	if typ == "Bool" {
		return "logic"
	}
	return "logic signed [63:0]"
}

func sourceOrMIRName(field MIRField) string {
	if field.SourceName != "" {
		return field.SourceName
	}
	return field.Name
}

func uniqueSVName(base string, used map[string]int) string {
	if used[base] == 0 {
		used[base] = 1
		return base
	}
	for suffix := used[base]; ; suffix++ {
		candidate := base + "_oct" + strconv.Itoa(suffix)
		if used[candidate] == 0 {
			used[base] = suffix + 1
			used[candidate] = 1
			return candidate
		}
	}
}

func sanitizeSVIdentifier(name string) string {
	var b strings.Builder
	for i, r := range name {
		valid := r == '_' || r == '$' || unicode.IsLetter(r) || (i > 0 && unicode.IsDigit(r))
		if valid && r <= unicode.MaxASCII {
			b.WriteRune(r)
		} else {
			b.WriteByte('_')
		}
	}
	result := b.String()
	if result == "" || unicode.IsDigit(rune(result[0])) || svKeywords[result] {
		result = "oct_" + result
	}
	return result
}

var svKeywords = func() map[string]bool {
	words := strings.Fields("always always_comb always_ff assign begin case default else end endcase endfunction endmodule function if input logic module output reg signed wire")
	sort.Strings(words)
	result := make(map[string]bool, len(words))
	for _, word := range words {
		result[word] = true
	}
	return result
}()
