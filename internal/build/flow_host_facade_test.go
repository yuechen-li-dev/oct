const flowTurnM1HostSpecimen = "../../experimental/flowturnm1/specimen/flow.oct"

func TestEmbeddableFlowHostFacadeCheckpointRestoreAndIndependence(t *testing.T) {
	source, err := EmitGoSource(flowTurnM1HostSpecimen, GoSourceOptions{PackageName: "generated"})
	if err != nil {
		t.Fatal(err)
	}
	text := string(source)
	for _, required := range []string{
		"type DurableController struct",
		"func NewDurableController(",
		"func RestoreDurableController(",
		"func (m *DurableController) Step(input Main_TurnMessage)",
		"func NewHostCommandAdd(payload int)",
		"func AdmitPositiveAmount(value int)",
	} {
		if !strings.Contains(text, required) {
			t.Fatalf("generated host facade omitted %q", required)
		}
	}

	dir := t.TempDir()
	generatedDir := filepath.Join(dir, "generated")
	consumerDir := filepath.Join(dir, "consumer")
	if err := os.MkdirAll(generatedDir, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.MkdirAll(consumerDir, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(generatedDir, "flow.generated.go"), source, 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "go.mod"), []byte("module flowhostprobe\n\ngo 1.22\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(consumerDir, "host_test.go"), []byte(flowHostFacadeHarness), 0o644); err != nil {
		t.Fatal(err)
	}
	historySource, err := EmitGoSource("../../experimental/flowturnm1/history/flow.oct", GoSourceOptions{PackageName: "historygenerated"})
	if err != nil {
		t.Fatal(err)
	}
	historyGeneratedDir := filepath.Join(dir, "historygenerated")
	historyConsumerDir := filepath.Join(dir, "historyconsumer")
	if err := os.MkdirAll(historyGeneratedDir, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.MkdirAll(historyConsumerDir, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(historyGeneratedDir, "flow.generated.go"), historySource, 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(historyConsumerDir, "history_test.go"), []byte(flowHistoryHostHarness), 0o644); err != nil {
		t.Fatal(err)
	}
	arguments := []string{"test", "-v", "./..."}
	if os.Getenv("OCT_FLOW_TURN_M1_BENCH") == "1" {
		arguments = []string{"test", "-v", "-run", "TestTypedFacadeAndExactRestore", "-bench", "Benchmark", "-benchmem", "-count=3", "./consumer"}
	}
	command := exec.Command("go", arguments...)
	command.Dir = dir
	output, err := command.CombinedOutput()
	if err != nil {
		t.Fatalf("independent generated package failed: %v\n%s", err, output)
	}
	t.Logf("generated bytes=%d; independent host output:\n%s", len(source), output)
}

const flowHostFacadeHarness = `package consumer_test

import (
    "bytes"
    "encoding/json"
    "errors"
    "testing"

    generated "flowhostprobe/generated"
)

var benchmarkYield int
var benchmarkCheckpoint generated.DurableControllerCheckpoint
var benchmarkMachine *generated.DurableController

func TestTypedFacadeAndExactRestore(t *testing.T) {
	 refinedMachine := generated.NewRefinedHost()
	 if _, err := refinedMachine.Step(-1); err == nil { t.Fatal("refined host input bypassed admission") }
	 admitted, err := generated.AdmitPositiveAmount(4)
	 if err != nil { t.Fatal(err) }
	 refinedTurn, err := refinedMachine.Step(admitted)
	 if err != nil { t.Fatal(err) }
	 refinedYield, _ := refinedTurn.Yielded()
	 if refinedYield != 4 { t.Fatalf("refined yield=%d", refinedYield) }

    first := generated.Main_TurnMessage{Amount: 3, PreferHigh: true}
    next := generated.Main_TurnMessage{Amount: 22, PreferHigh: false}
    machine := generated.NewDurableController(1)
    turn, err := machine.Step(first)
    if err != nil { t.Fatal(err) }
    yielded, err := turn.Yielded()
    if err != nil || yielded != 6 { t.Fatalf("first yield=%v err=%v", yielded, err) }

    checkpoint, err := machine.Checkpoint()
    if err != nil { t.Fatal(err) }
    checkpointAgain, err := machine.Checkpoint()
    if err != nil { t.Fatal(err) }
    if !bytes.Equal(checkpoint.Bytes(), checkpointAgain.Bytes()) { t.Fatal("checkpoint bytes are not deterministic") }

    restored, err := generated.RestoreDurableController(checkpoint)
    if err != nil { t.Fatal(err) }
    baselineTurn, err := machine.Step(next)
    if err != nil { t.Fatal(err) }
    restoredTurn, err := restored.Step(next)
    if err != nil { t.Fatal(err) }
    baselineYield, _ := baselineTurn.Yielded()
    restoredYield, _ := restoredTurn.Yielded()
    if baselineYield != 29 || restoredYield != baselineYield { t.Fatalf("continuation baseline=%d restored=%d", baselineYield, restoredYield) }
    baselineBoard, _ := machine.Board()
    restoredBoard, _ := restored.Board()
    if baselineBoard != restoredBoard { t.Fatalf("board mismatch: %#v %#v", baselineBoard, restoredBoard) }

    generator := generated.NewNumberGenerator()
    generatorTurn, _ := generator.Step()
    firstNumber, _ := generatorTurn.Yielded()
    generatorCheckpoint, _ := generator.Checkpoint()
	 t.Logf("checkpoint bytes: durable=%d generator=%d", len(checkpoint.Bytes()), len(generatorCheckpoint.Bytes()))
    generator2, err := generated.RestoreNumberGenerator(generatorCheckpoint)
    if err != nil { t.Fatal(err) }
    generatorTurn2, _ := generator2.Step()
    secondNumber, _ := generatorTurn2.Yielded()
    if firstNumber != 1 || secondNumber != 2 { t.Fatalf("generator restore: %d then %d", firstNumber, secondNumber) }

    enumMachine := generated.NewHostEnum()
    enumTurn, err := enumMachine.Step(generated.NewHostCommandAdd(3))
    if err != nil { t.Fatal(err) }
    enumYield, _ := enumTurn.Yielded()
    if enumYield != 3 { t.Fatalf("enum yield=%d", enumYield) }
	 enumCheckpoint, err := enumMachine.Checkpoint()
	 if err != nil { t.Fatal(err) }
	 t.Logf("checkpoint bytes: plain=%d durable=%d generator=%d", len(enumCheckpoint.Bytes()), len(checkpoint.Bytes()), len(generatorCheckpoint.Bytes()))

	 validationCases := []struct {
	     name string
	     field string
	     value any
	     reason generated.DurableControllerCheckpointReason
	 }{
	     {"version", "version", float64(99), generated.DurableControllerVersionMismatch},
	     {"flow", "flow", "Other", generated.DurableControllerFlowMismatch},
	     {"fingerprint", "fingerprint", "changed", generated.DurableControllerFingerprintMismatch},
	     {"state", "current_state", "Missing", generated.DurableControllerStateMissing},
	     {"continuation", "instruction", float64(99), generated.DurableControllerContinuationInvalid},
	     {"board", "board_schema", "changed", generated.DurableControllerBoardSchemaMismatch},
	     {"construction", "construction_schema", "changed", generated.DurableControllerConstructionMismatch},
	     {"utility", "utility_schema", "changed", generated.DurableControllerUtilitySiteMismatch},
	     {"yield", "yield_schema", "changed", generated.DurableControllerYieldSchemaMismatch},
	 }
	 for _, testCase := range validationCases {
	     t.Run(testCase.name, func(t *testing.T) {
	         var raw map[string]any
	         if err := json.Unmarshal(checkpoint.Bytes(), &raw); err != nil { t.Fatal(err) }
	         raw[testCase.field] = testCase.value
	         altered, _ := json.Marshal(raw)
	         parsed, err := generated.ParseDurableControllerCheckpoint(altered)
	         if err != nil { t.Fatal(err) }
	         _, err = generated.RestoreDurableController(parsed)
	         var checkpointErr generated.DurableControllerCheckpointError
	         if !errors.As(err, &checkpointErr) || checkpointErr.Reason != testCase.reason {
	             t.Fatalf("reason=%#v err=%v", checkpointErr, err)
	         }
	     })
    }
}

func BenchmarkFacadeStepYield(b *testing.B) {
    machine := generated.NewDurableController(1)
    message := generated.Main_TurnMessage{Amount: 3, PreferHigh: true}
    b.ReportAllocs()
    for index := 0; index < b.N; index++ {
        turn, err := machine.Step(message)
        if err != nil { b.Fatal(err) }
        benchmarkYield, err = turn.Yielded()
        if err != nil { b.Fatal(err) }
    }
}

func BenchmarkCheckpoint(b *testing.B) {
    machine := generated.NewDurableController(1)
    machine.Step(generated.Main_TurnMessage{Amount: 3, PreferHigh: true})
    b.ReportAllocs()
    for index := 0; index < b.N; index++ {
        checkpoint, err := machine.Checkpoint()
        if err != nil { b.Fatal(err) }
        benchmarkCheckpoint = checkpoint
    }
}

func BenchmarkRestore(b *testing.B) {
    machine := generated.NewDurableController(1)
    machine.Step(generated.Main_TurnMessage{Amount: 3, PreferHigh: true})
    checkpoint, _ := machine.Checkpoint()
    b.ReportAllocs()
    for index := 0; index < b.N; index++ {
        restored, err := generated.RestoreDurableController(checkpoint)
        if err != nil { b.Fatal(err) }
        benchmarkMachine = restored
    }
}
`

