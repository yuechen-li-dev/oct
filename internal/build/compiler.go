type Result struct {
	ArtifactPath        string
	GeneratedSourcePath string
	MIRDumpPath         string
}

const generatedGoHeader = "// Code generated by Oct's compiled backend. DO NOT EDIT.\n"

// GoSourceOptions controls the deliberately narrow source-only compiled seam.
// Source emitted through this seam is embeddable in an ordinary Go package:
// it contains the existing compiled runtime implementation but no process
// entrypoint. The normal Compile path remains package main plus func main.
type GoSourceOptions struct {
	PackageName string
}

// EmitGoSource loads, type-checks, lowers, and emits an Oct program without
// invoking go build or writing a file. It is internal and experimental rather
// than a stable compiler framework API.
func EmitGoSource(path string, options GoSourceOptions) ([]byte, error) {
	if !token.IsIdentifier(options.PackageName) || token.Lookup(options.PackageName).IsKeyword() {
		return nil, fmt.Errorf("invalid Go package name %q", options.PackageName)
	}
	program, err := project.Load(path)
	if err != nil {
		return nil, err
	}
	if err := typecheck.CheckProgram(program); err != nil {
		return nil, err
	}
	module, err := lowerProgram(program, compileOptions{})
	if err != nil {
		return nil, err
	}
	source, err := emitGoWithOptions(module, goEmitOptions{packageName: options.PackageName, hostFacade: true})
	if err != nil {
		return nil, err
	}
	formatted, err := format.Source([]byte(source))
	if err != nil {
		return nil, fmt.Errorf("format emitted Go source: %w", err)
	}
	return append([]byte(generatedGoHeader), formatted...), nil
}

func Compile(path string) (Result, error) {
	program, err := project.Load(path)
	if err != nil {
		return Result{}, err
	}
	return compileProgram(program, compileOptions{})
}

func CompileForTest(path string) (Result, error) {
	program, err := project.LoadForTest(path)
	if err != nil {
		return Result{}, err
	}
	return compileProgram(program, compileOptions{selectedReachableOnly: true, testArtifactLayout: true})
}

type compileOptions struct {
	selectedReachableOnly bool
	testHarnessCases      []TestHarnessCase
	testArtifactLayout    bool
	allowNoEntry          bool
}

// TestHarnessCase is one already-lowered, zero-argument Oct helper function.
// It is intentionally small so tester can request a reusable native harness
// without giving build package knowledge of Octest metadata.
type TestHarnessCase struct {
	ID       string
	Function string
}

func compileProgram(program project.Program, options compileOptions) (Result, error) {
	if err := typecheck.CheckProgram(program); err != nil {
		return Result{}, err
	}

	if program.Profile == "Verilog" {
		options.allowNoEntry = true
	}
	module, err := lowerProgram(program, options)
	if err != nil {
		return Result{}, err
	}
	if program.Profile == "Verilog" {
		if len(options.testHarnessCases) > 0 {
			return Result{}, fmt.Errorf("Verilog profile does not support Octest harness compilation in M0")
		}
		if err := CheckSystemVerilogLegal(module); err != nil {
			return Result{}, err
		}
		source, err := emitSystemVerilog(module)
		if err != nil {
			return Result{}, err
		}
		artifactPath := systemVerilogOutputPath(program.EntrySource)
		if err := os.WriteFile(artifactPath, []byte(source), 0o644); err != nil {
			return Result{}, fmt.Errorf("write generated SystemVerilog %s: %w", artifactPath, err)
		}
		res := Result{ArtifactPath: artifactPath, GeneratedSourcePath: artifactPath}
		if os.Getenv("OCT_MIR_DUMP") != "" {
			dumpPath := artifactPath + ".mir"
			if err := os.WriteFile(dumpPath, []byte(dumpMIR(module)), 0o644); err != nil {
				return Result{}, fmt.Errorf("write MIR dump %s: %w", dumpPath, err)
			}
			res.MIRDumpPath = dumpPath
		}
		return res, nil
	}

	goSrc, err := emitGo(module)
	if err != nil {
		return Result{}, err
	}
	if len(options.testHarnessCases) > 0 {
		goSrc, err = injectTestHarnessMain(goSrc, module.EntryPackage, options.testHarnessCases)
		if err != nil {
			return Result{}, err
		}
	}

	artifactKind := ArtifactExecutable
	if len(options.testHarnessCases) > 0 {
		artifactKind = ArtifactTestExecutable
	}
	artifactPath := programOutputPath(program.EntrySource, artifactKind, HostTarget())
	genPath := ""
	if options.testArtifactLayout {
		paths, err := DeriveTestArtifactPaths(program.EntrySource, HostTarget())
		if err != nil {
			return Result{}, err
		}
		artifactPath, genPath = paths.Binary, paths.GeneratedSource
		if err := os.MkdirAll(filepath.Dir(genPath), 0o755); err != nil {
			return Result{}, fmt.Errorf("create compiled test artifact directory %s: %w", filepath.Dir(genPath), err)
		}
	} else {
		genDir, err := generatedBuildDir()
		if err != nil {
			return Result{}, err
		}
		if os.Getenv("OCT_KEEP_GEN") == "" {
			defer os.RemoveAll(genDir)
		}
		genPath = filepath.Join(genDir, filepath.Base(artifactPath)+".gen.go")
	}
	if filepath.Clean(genPath) == filepath.Clean(artifactPath) {
		return Result{}, fmt.Errorf("generated source path collides with binary output path: %s", artifactPath)
	}
	if err := os.WriteFile(genPath, []byte(goSrc), 0o644); err != nil {
		return Result{}, fmt.Errorf("write generated go %s: %w", genPath, err)
	}
	buildSourcePath := genPath
	if strings.Contains(goSrc, `github.com/yuechen-li-dev/oct/internal/`) {
		// Go's internal-package rule is based on the generated source file's
		// directory, not the compiler process working directory. Compiled test
		// artifacts intentionally live in an OS-temp lifecycle scope, so stage a
		// transient build input beneath the module while retaining that external
		// artifact layout for runner cleanup and diagnostics.
		stageDir, err := generatedBuildDir()
		if err != nil {
			return Result{}, err
		}
		if os.Getenv("OCT_KEEP_GEN") == "" {
			defer os.RemoveAll(stageDir)
		}
		buildSourcePath = filepath.Join(stageDir, filepath.Base(genPath))
		if err := os.WriteFile(buildSourcePath, []byte(goSrc), 0o644); err != nil {
			return Result{}, fmt.Errorf("write staged generated go %s: %w", buildSourcePath, err)
		}
	}

	if options.testArtifactLayout {
		// A failed rebuild must not be able to execute a previous owned binary.
		if err := os.Remove(artifactPath); err != nil && !os.IsNotExist(err) {
			return Result{}, fmt.Errorf("remove stale compiled test binary %s: %w", artifactPath, err)
		}
	}
	cmd := exec.Command("go", "build", "-o", artifactPath, buildSourcePath)
	moduleRoot, err := compilerModuleRoot()
	if err != nil {
		return Result{}, err
	}
	cmd.Dir = moduleRoot
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	if err := cmd.Run(); err != nil {
		return Result{}, fmt.Errorf("go build generated program: %v: %s", err, strings.TrimSpace(stderr.String()))
	}

	if info, err := os.Stat(artifactPath); err != nil || info.IsDir() {
		if err != nil {
			return Result{}, fmt.Errorf("compiled output missing after successful go build: %s: %w", artifactPath, err)
		}
		return Result{}, fmt.Errorf("compiled output missing after successful go build: %s is a directory", artifactPath)
	}
	res := Result{ArtifactPath: artifactPath, GeneratedSourcePath: genPath}
	if os.Getenv("OCT_MIR_DUMP") != "" {
		dumpPath := artifactPath + ".mir"
		if err := os.WriteFile(dumpPath, []byte(dumpMIR(module)), 0o644); err != nil {
			return Result{}, fmt.Errorf("write MIR dump %s: %w", dumpPath, err)
		}
		res.MIRDumpPath = dumpPath
	}
	return res, nil
}

func systemVerilogOutputPath(entrySource string) string {
	if info, err := os.Stat(entrySource); err == nil && info.IsDir() {
		clean := filepath.Clean(entrySource)
		return filepath.Join(clean, filepath.Base(clean)+".sv")
	}
	ext := filepath.Ext(entrySource)
	return strings.TrimSuffix(entrySource, ext) + ".sv"
}

func generatedBuildDir() (string, error) {
	root, err := compilerModuleRoot()
	if err != nil {
		return "", err
	}
	parent := filepath.Join(root, ".octbuild")
	if err := os.MkdirAll(parent, 0o755); err != nil {
		return "", fmt.Errorf("create generated build directory %s: %w", parent, err)
	}
	dir, err := os.MkdirTemp(parent, "gen-")
	if err != nil {
		return "", fmt.Errorf("create generated build temp dir: %w", err)
	}
	return dir, nil
}

func programOutputPath(source string, kind ArtifactKind, target Target) string {
	path := OutputPath(filepath.Join(filepath.Dir(source), filepath.Base(source)), kind, target)
	if filepath.Clean(path) == filepath.Clean(source) {
		return path + ".out"
	}
	return path
}

func compilerModuleRoot() (string, error) {
	if configured := strings.TrimSpace(os.Getenv("OCT_COMPILER_RUNTIME")); configured != "" {
		return validateCompilerModuleRoot(configured)
	}
	if executable, err := os.Executable(); err == nil {
		candidate := filepath.Join(filepath.Dir(executable), "runtime")
		if _, err := os.Stat(filepath.Join(candidate, "go.mod")); err == nil {
			return validateCompilerModuleRoot(candidate)
		}
	}
	_, file, _, ok := runtime.Caller(0)
	if !ok {
		return "", fmt.Errorf("locate compiler module root: runtime caller unavailable")
	}
	return validateCompilerModuleRoot(filepath.Join(filepath.Dir(file), "..", ".."))
}

func validateCompilerModuleRoot(root string) (string, error) {
	root = filepath.Clean(root)
	info, err := os.Stat(filepath.Join(root, "go.mod"))
	if err != nil {
		return "", fmt.Errorf("locate compiler runtime at %s: %w", root, err)
	}
	if info.IsDir() {
		return "", fmt.Errorf("locate compiler runtime at %s: go.mod is a directory", root)
	}
	return root, nil
}

func CompileForTestWithSelectedFiles(path string, selectedFiles []string) (Result, error) {
	program, err := project.LoadForTestWithSelectedFiles(path, selectedFiles)
	if err != nil {
		return Result{}, err
	}
	return compileProgram(program, compileOptions{selectedReachableOnly: true, testArtifactLayout: true})
}

// CompileForTestWithSelectedFilesInPackage compiles an externally stored test
// runner against the package rooted at packageDir. The output follows the
// runner into its owned temporary directory; ordinary Compile outputs are
// unchanged and remain persistent.
func CompileForTestWithSelectedFilesInPackage(path string, packageDir string, selectedFiles []string) (Result, error) {
	program, err := project.LoadForTestWithSelectedFilesInPackage(path, packageDir, selectedFiles)
	if err != nil {
		return Result{}, err
	}
	return compileProgram(program, compileOptions{selectedReachableOnly: true, testArtifactLayout: true})
}

// CompileTestHarnessWithSelectedFilesInPackage emits one native executable
// that dispatches to the supplied generated helper functions by --case ID.
func CompileTestHarnessWithSelectedFilesInPackage(path string, packageDir string, selectedFiles []string, cases []TestHarnessCase, wrappers []project.WrapperMetadata) (Result, error) {
	program, err := project.LoadForTestWithSelectedFilesInPackage(path, packageDir, selectedFiles)
	if err != nil {
		return Result{}, err
	}
	if len(wrappers) > 0 {
		pkg := program.Packages[program.Entry]
		pkg.Wrappers = append([]project.WrapperMetadata(nil), wrappers...)
		program.Packages[program.Entry] = pkg
	}
	return compileProgram(program, compileOptions{selectedReachableOnly: true, testHarnessCases: cases, testArtifactLayout: true})
}

func injectTestHarnessMain(src, pkg string, cases []TestHarnessCase) (string, error) {
	start := strings.Index(src, "func main() {")
	if start < 0 {
		return "", fmt.Errorf("generated program has no main function")
	}
	open := start + len("func main() ")
	depth := 0
	end := -1
	for i := open; i < len(src); i++ {
		switch src[i] {
		case '{':
			depth++
		case '}':
			depth--
			if depth == 0 {
				end = i + 1
				i = len(src)
			}
		}
	}
	if end < 0 {
		return "", fmt.Errorf("generated main function is malformed")
	}
	var b strings.Builder
	b.WriteString("func main() {\n")
	b.WriteString("\tif len(os.Args) != 3 || os.Args[1] != \"--case\" { fmt.Fprintln(os.Stderr, \"usage: harness --case <stable-id>\"); os.Exit(2) }\n")
	b.WriteString("\tdiagnostic := __octRunMain(func() {\n")
	b.WriteString("\t\tswitch os.Args[2] {\n")
	for _, tc := range cases {
		fmt.Fprintf(&b, "\t\tcase %q:\n\t\t\tfn_%s_%s()\n\t\t\tfmt.Printf(\"{\\\"case_id\\\":%%q,\\\"status\\\":\\\"pass\\\"}\\n\", os.Args[2])\n", tc.ID, pkg, tc.Function)
	}
	b.WriteString("\t\tdefault: fmt.Fprintln(os.Stderr, \"unknown test case\"); os.Exit(2)\n\t\t}\n")
	b.WriteString("\t})\n")
	b.WriteString("\tif diagnostic != \"\" { fmt.Fprintln(os.Stderr, diagnostic); os.Exit(1) }\n")
	b.WriteString("}\n")
	return src[:start] + b.String() + src[end:], nil
}
